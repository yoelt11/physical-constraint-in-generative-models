"""Labeled schematic of the four-bar linkage at a single joint angle.

Anchors x1, x2 (fixed, never generated) are drawn in a different color and
marker than the free nodes x3, x4 (generated by the flow-matching model),
with every node labeled and every link annotated with its length symbol.
"""

import numpy as np
import matplotlib.pyplot as plt

from visualize_problem import X1, X2, L12, L23, L34, L41, solve_linkage, save_figure

ANCHOR_COLOR = "#2b2b2b"
FREE_COLOR = "#d95f02"
THETA_DEG = 55.0


def midpoint(a, b):
    return 0.5 * (a + b)


def main():
    theta = np.radians(THETA_DEG)
    x3, solutions = solve_linkage(theta)
    x4 = solutions[+1]

    fig, ax = plt.subplots(figsize=(6, 6))

    links = [(X1, X2, r"$\ell_{12}$"), (X2, x3, r"$\ell_{23}$"),
             (x3, x4, r"$\ell_{34}$"), (x4, X1, r"$\ell_{41}$")]
    for a, b, label in links:
        ax.plot([a[0], b[0]], [a[1], b[1]], "-", color="#888888", lw=2.5, zorder=1)
        m = midpoint(a, b)
        ax.annotate(label, m, textcoords="offset points", xytext=(4, -12),
                     fontsize=11, color="#555555")

    anchors = [(X1, "$x_1$"), (X2, "$x_2$")]
    free = [(x3, "$x_3$"), (x4, "$x_4$")]
    ax.scatter(*np.array([p for p, _ in anchors]).T, color=ANCHOR_COLOR,
               marker="s", s=140, zorder=3, label="anchor (fixed)")
    ax.scatter(*np.array([p for p, _ in free]).T, color=FREE_COLOR,
               marker="o", s=140, zorder=3, label="free (generated)")
    for point, label in anchors + free:
        ax.annotate(label, point, textcoords="offset points", xytext=(10, 10),
                     fontsize=13)

    # Joint angle arc at x2, between the ground link direction (x2 -> x1)
    # and the crank direction (x2 -> x3).
    arc_radius = 0.22
    start_angle = 180.0  # direction from x2 back to x1
    arc = np.linspace(np.radians(start_angle), theta, 60)
    arc_pts = X2 + arc_radius * np.c_[np.cos(arc), np.sin(arc)]
    ax.plot(*arc_pts.T, color="black", lw=1)
    label_angle = (np.radians(start_angle) + theta) / 2
    label_pt = X2 + (arc_radius + 0.07) * np.array([np.cos(label_angle), np.sin(label_angle)])
    ax.annotate(r"$\theta$", label_pt, fontsize=12, ha="center")

    ax.set_title(r"Four-bar linkage: fixed anchors $x_1,x_2$, free nodes $x_3,x_4$"
                 + f"\n(shown at $\\theta={THETA_DEG:.0f}\\degree$, branch $b=+1$)")
    ax.set_aspect("equal")
    ax.set_xlabel("$x$")
    ax.set_ylabel("$y$")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.08), ncol=2, fontsize=9)
    fig.tight_layout()
    save_figure(fig, "mechanism_schematic", bbox_inches="tight")


if __name__ == "__main__":
    main()
